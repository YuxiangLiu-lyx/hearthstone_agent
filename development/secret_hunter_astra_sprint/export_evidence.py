"""Portable frozen evidence archive; private auth/transcripts are excluded."""
import json,sqlite3,tarfile,time
from pathlib import Path
from development.secret_hunter_astra_sprint.study import ROOT,RUN
from development.secret_hunter_astra_sprint import ledger
from development.secret_hunter_program.common import sha

def main():
 db=ledger.connect(RUN);assert not ledger.meta(db,'pid') and not ledger.meta(db,'cf_pid')
 assert all(db.execute('select status from batches where id=?',(b,)).fetchone()[0]=='done' for b in ('final-core','final-guard'))
 recommendation=ROOT/'docs/secret_hunter_astra_sprint/recommendation.json';assert recommendation.exists()
 acceptance=RUN/'final-acceptance.json';assert acceptance.exists(),'Record actual protocol acceptance or explicit environment gap first'
 counts={'full_match_attempts':db.execute('select count(*) from attempts').fetchone()[0],
         'auxiliary_attempts':db.execute('select count(*) from auxiliary_games').fetchone()[0],
         'continuation_attempts':db.execute('select count(*) from cf_attempts').fetchone()[0],
         'full_status':dict(db.execute('select status,count(*) from attempts group by status').fetchall()),
         'auxiliary_status':dict(db.execute('select status,count(*) from auxiliary_games group by status').fetchall()),
         'continuation_status':dict(db.execute('select status,count(*) from cf_attempts group by status').fetchall())}
 counts['total_full_attempts']=counts['full_match_attempts']+counts['auxiliary_attempts'];m=ledger.meta(db,'manifest')
 counts.update(started_utc=m['created'],completed_utc=time.time(),deadline_utc=m['deadline'],elapsed_s=time.time()-m['created'],limits=m['limits'])
 assert counts['total_full_attempts']<=18000 and counts['continuation_attempts']<=16000 and time.time()<=m['deadline']
 ledger.atomic(RUN/'final-budget-audit.json',counts);ledger.atomic(ROOT/'docs/secret_hunter_astra_sprint/final-budget-audit.json',counts)
 snapshot=RUN/'ledger.final.sqlite';target=sqlite3.connect(snapshot);db.backup(target);target.close()
 files={p for p in RUN.glob('*.json') if p.is_file()}
 for sub,pattern in [('frozen','*.zip'),('hypotheses','*.json'),('tactical-sources','*.json'),('harness-by-sha','*.json'),('case-replays','*.json')]:
  files.update((RUN/sub).glob(pattern))
 for batch in db.execute('select id from batches'):
  report=RUN/'batches'/batch[0]/'report.json'
  if report.exists():files.add(report)
 for p in (RUN/'relay').glob('*.audit.json'):files.add(p)
 # Exact logs for selected final examples are sufficient to replay every
 # public prefix/action/terminal. Other full games can be regenerated by seed.
 case_audit=RUN/'final-case-replay-audit.json'
 if case_audit.exists():
  for record in json.loads(case_audit.read_text()):
   replay=json.loads(Path(record['path']).read_text());folder=Path(replay['source_game'])
   files.update(p for p in folder.rglob('*') if p.is_file() and p.suffix in ('.json','.jsonl'))
 manifest={'created':time.time(),'budget':counts,'files':{str(p.relative_to(RUN)):sha(p) for p in sorted(files)},
           'ledger_sqlite_sha256':sha(snapshot),'scope':'Exact frozen ZIPs, immutable analysis/reproduction metadata, full task ledger, public roots, and selected verified final-game logs. Full raw training logs remain in the original local run. No authentication files or model session transcripts.'}
 ledger.atomic(RUN/'evidence-index.json',manifest);files.add(RUN/'evidence-index.json')
 out=ROOT/'docs/secret_hunter_astra_sprint/evidence.tar.gz'
 with tarfile.open(out,'w:gz',compresslevel=6) as tar:
  for p in sorted(files):tar.add(p,arcname=str(Path('astra-sprint-evidence')/p.relative_to(RUN)),recursive=False)
  tar.add(snapshot,arcname='astra-sprint-evidence/ledger.sqlite',recursive=False)
 record={'archive':str(out.relative_to(ROOT)),'sha256':sha(out),'bytes':out.stat().st_size,'files':len(files)+1,'budget':counts,'scope':manifest['scope']}
 ledger.atomic(ROOT/'docs/secret_hunter_astra_sprint/evidence-index.json',record);print(json.dumps(record,indent=2))
if __name__=='__main__':main()
